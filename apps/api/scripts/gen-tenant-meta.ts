// Regenerates src/database/tenant/meta.generated.ts from schema.prisma. Runs as part of `pnpm db:generate`.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { parseSchemaMeta } from '../src/database/tenant/parse-schema';

const root = path.resolve(import.meta.dirname, '..');
const schema = readFileSync(path.join(root, 'src/database/prisma/schema.prisma'), 'utf8');
const meta = parseSchemaMeta(schema);
const out =
  `// GENERATED by scripts/gen-tenant-meta.ts from schema.prisma. Do not edit.\n` +
  `import type { TenantMeta } from './types';\n\n` +
  `export const tenantMeta: TenantMeta = ${JSON.stringify(meta, null, 2)};\n`;
writeFileSync(path.join(root, 'src/database/tenant/meta.generated.ts'), out);
console.log(`tenant metadata written for ${Object.keys(meta).length} models`);
